# Surefire has the default inclusion pattern
# https://maven.apache.org/surefire/maven-surefire-plugin/test-mojo.html#includes
# and the default exclusion pattern
# https://maven.apache.org/surefire/maven-surefire-plugin/test-mojo.html#excludes
# these variables emulates those effects.
# TODO: inclusion/exclusion are user configurable patterns, so it should be user configurable
# beyond that and to fully generalize this, there's internal discussion of
# this at https://launchableinc.atlassian.net/l/c/TXDJnn09
includes = [uglob.compile(x) for x in [
    # HACK: we check extensions outside the glob. We seem to allow both source
    # file enumeration and class file enumeration
    '**/Test*.*',
    '**/*Test.*',
    '**/*Spec.*',
    '**/*Tests.*',
    '**/*TestCase.*'
]]
excludes = [uglob.compile(x) for x in [
    '**/*$*'
]]

# Test if a given path name is a test that Surefire recognizes


def is_file(f: str) -> bool:
    if not (f.endswith('.java') or f.endswith(".scala") or f.endswith(".kt") or f.endswith(".class") or f.endswith(".groovy")):
        return False
    for p in excludes:
        if p.fullmatch(f):
            return False
    for p in includes:
        if p.fullmatch(f):
            return True
    return False


def parse_surefire_reports() -> List[Dict[str, str]]:
    """Collect the test classes Surefire discovered from its TEST-*.xml reports.

    Intended to be run against reports produced by a JUnit 5 dry run
    (`mvn test -Djunit.platform.execution.dryRun.enabled=true`): Surefire applies
    all of its own filtering (excludedGroups, includedGroups, excludes, profiles,
    ...) before the dry run, so only the tests Maven would actually execute get a
    report. Each report's root `name` attribute is the fully-qualified class name.
    """
    test_paths = []
    report_pattern = os.path.join('**', 'target', 'surefire-reports', 'TEST-*.xml')
    report_files = glob.glob(report_pattern, recursive=True)

    for report_file in report_files:
        try:
            if classname := ET.parse(report_file).getroot().get('name'):
                test_paths.append({"type": "class", "name": classname})
        except ET.ParseError as e:
            click.secho(f"Warning: Could not parse {report_file}: {e}", fg='yellow', err=True)

    return test_paths


@smart_tests.subset
def subset(
    client: Subset,
    source_roots: Annotated[List[str] | None, typer.Argument(
        multiple=True,
        required=False,
        help="Source root directories to scan for tests"
    )] = None,
    test_compile_created_file: Annotated[List[str] | None, typer.Option(
        "--test-compile-created-file",
        multiple=True,
        help="Please run `mvn test-compile` command to create input file for this option"
    )] = None,
    is_scan_test_compile_lst: Annotated[bool, typer.Option(
        "--scan-test-compile-lst",
        help="Scan testCompile/default-testCompile/createdFiles.lst for *.lst files generated by `mvn compile` and "
             "use them as test inputs."
    )] = False,
    is_scan_dryrun_results: Annotated[bool, typer.Option(
        "--scan-dryrun-results",
        help="Scan surefire reports generated by `mvn test -Djunit.platform.execution.dryRun.enabled=true`. "
             "Only the tests Maven would actually run (after applying pom.xml excludedGroups/excludes/etc.) are "
             "sent to the subset. Run the dry run before this command. JUnit 5 only."
    )] = False,
    exclude_rules: Annotated[List[str], typer.Option(
        "--exclude",
        multiple=True,
        help="Exclude tests matching the given Python regular expression pattern. Can be specified multiple times."
    )] = [],
):
    # Compile exclude rules
    compiled_exclude_rules = []
    for rule in exclude_rules:
        try:
            compiled_exclude_rules.append(re.compile(rule))
        except re.error as e:
            raise BadCmdLineException("Invalid regular expression '{}': {}".format(rule, e))

    def file2class_test_path(f: str) -> List[Dict[str, str]]:
        # remove extension
        f, _ = os.path.splitext(f)

        # directory -> package name conversion
        cls_name = f.replace(os.path.sep, '.')
        return [{"type": "class", "name": cls_name}]

    def file2test(f: str) -> List | None:
        if is_file(f):
            test_path = file2class_test_path(f)

            for pattern in compiled_exclude_rules:
                if pattern.search(test_path[0]["name"]):
                    return None

            return test_path
        else:
            return None

    # Handle None values
    if test_compile_created_file is None:
        test_compile_created_file = []
    if source_roots is None:
        source_roots = []

    if is_scan_dryrun_results:
        tests = parse_surefire_reports()
        if not tests:
            raise BadCmdLineException(
                "No surefire reports found under **/target/surefire-reports/. "
                "Run `mvn test -Djunit.platform.execution.dryRun.enabled=true` before this command.")
        for test in tests:
            client.test_paths.append([test])
        client.same_bin_formatter = lambda s: [{"type": "class", "name": s}]
        client.run()
        return

    files_to_read = list(test_compile_created_file)
    if is_scan_test_compile_lst:
        if len(test_compile_created_file) > 0:
            click.echo(click.style(
                "Warning: --test-compile-created-file is overridden by --scan-test-compile-lst", fg="yellow"),
                err=True)
        pattern = os.path.join('**', 'createdFiles.lst')
        files_to_read = glob.glob(pattern, recursive=True)

        if not files_to_read:
            click.echo(click.style(
                "Warning: No .lst files. Please run after executing `mvn test-compile`", fg="yellow"),
                err=True)
            return

    if files_to_read:
        for file in files_to_read:
            with open(file, 'r') as f:
                lines = f.readlines()
                if len(lines) == 0:
                    click.secho(
                        f"Warning: --test-compile-created-file {file} is empty",
                        fg='yellow',
                        err=True)

                for line in lines:
                    # trim trailing newline
                    line = line.strip()

                    path = file2test(line)
                    if path:
                        client.test_paths.append(path)
    else:
        for root in source_roots:
            client.scan(root, '**/*', file2test)

    client.same_bin_formatter = lambda s: [{"type": "class", "name": s}]

    client.run()


# TestNG produces surefire-reports/testng-results.xml in TestNG's native format.
# Surefire produces TEST-*.xml in JUnit format (see Surefire's StatelessXmlReporter.getReportFile)
# In addition, TestNG also produces surefire-reports/junitreports/TEST-*.xml
# (see TestNG's JUnitReportReporter.getFileName)
# And there are more test reports in play.
#
# So to collectly find tests without duplications, we need to find surefire-reports/TEST-*.xml
# not surefire-reports/**/TEST-*.xml nor surefire-reports/*.xml
@smart_tests.record.tests
def record_tests(
    client: RecordTests,
    reports: Annotated[List[str], typer.Argument(
        multiple=True,
        help="Test report files to process"
    )],
):
    client.path_builder = junit5_nested_class_path_builder(client.path_builder)

    # Override report method to filter out non-JUnit report files
    original_report = client.report

    IGNORED_FILES = {'failsafe-summary.xml', 'testng-results.xml'}

    def report_with_filter(junit_report_file: str):
        if not any(junit_report_file.endswith(f) for f in IGNORED_FILES):
            original_report(junit_report_file)

    client.report = report_with_filter  # type: ignore[method-assign]
    smart_tests.CommonRecordTestImpls.load_report_files(client=client, source_roots=reports)
